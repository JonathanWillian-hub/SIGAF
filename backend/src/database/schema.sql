
CREATE SCHEMA IF NOT EXISTS {{SCHEMA}};
SET search_path TO {{SCHEMA}};

DROP TABLE IF EXISTS chamado_anexos, chamado_mensagens, chamados, logs_auditoria, notificacoes, relatorios, registros_atividade, usuarios, disciplinas, setores CASCADE;
DROP TYPE IF EXISTS perfil_usuario, categoria_atividade, status_atividade, formato_relatorio, status_relatorio, acao_log;

CREATE TYPE perfil_usuario      AS ENUM ('COLABORADOR', 'GESTOR', 'ADMINISTRADOR');
CREATE TYPE categoria_atividade AS ENUM ('ATIVIDADE_EXTRAORDINARIA', 'SUBSTITUICAO', 'COBERTURA_HORARIO', 'APOIO_OPERACIONAL');
CREATE TYPE status_atividade    AS ENUM ('PENDENTE', 'HOMOLOGADO', 'REJEITADO');
CREATE TYPE formato_relatorio   AS ENUM ('PDF', 'EXCEL', 'CSV');
CREATE TYPE status_relatorio    AS ENUM ('PROCESSANDO', 'CONCLUIDO', 'ERRO');
CREATE TYPE acao_log            AS ENUM ('CRIACAO', 'ALTERACAO', 'ELIMINACAO', 'LOGIN', 'HOMOLOGACAO', 'REJEICAO', 'RELATORIO');

CREATE TABLE setores (
  id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome    VARCHAR(120) NOT NULL,
  codigo  VARCHAR(20)  NOT NULL UNIQUE,
  ativo   BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE disciplinas (
  id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome      VARCHAR(120) NOT NULL,
  descricao VARCHAR(255),
  ativo     BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE usuarios (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        VARCHAR(120)   NOT NULL,
  matricula   VARCHAR(20)    NOT NULL UNIQUE,
  cpf         VARCHAR(255)   NOT NULL,
  email       VARCHAR(160)   NOT NULL UNIQUE,
  senha_hash  VARCHAR(100)   NOT NULL,
  perfil      perfil_usuario NOT NULL DEFAULT 'COLABORADOR',
  setor_id    INT REFERENCES setores(id),
  ativo       BOOLEAN        NOT NULL DEFAULT TRUE,
  cargo       VARCHAR(80),
  telefone    VARCHAR(20),
  foto        TEXT,
  notificar_email BOOLEAN    NOT NULL DEFAULT TRUE,
  criado_em   TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE registros_atividade (
  id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria          categoria_atividade NOT NULL,
  data               DATE        NOT NULL,
  horario_inicio     TIME        NOT NULL,
  horario_fim        TIME        NOT NULL,
  descricao_tarefas  TEXT        NOT NULL,
  data_criacao       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  executor_id        INT         NOT NULL REFERENCES usuarios(id),
  substituido_id     INT         REFERENCES usuarios(id),
  disciplina_id      INT         REFERENCES disciplinas(id),
  setor_id           INT         NOT NULL REFERENCES setores(id),
  criado_por_id      INT         NOT NULL REFERENCES usuarios(id),
  status             status_atividade NOT NULL DEFAULT 'PENDENTE',
  justificativa      VARCHAR(500),
  homologado_por_id  INT         REFERENCES usuarios(id),
  homologado_em      TIMESTAMPTZ,
  CHECK (horario_fim > horario_inicio)
);
CREATE INDEX idx_reg_data ON registros_atividade (data);
CREATE INDEX idx_reg_setor ON registros_atividade (setor_id);
CREATE INDEX idx_reg_executor ON registros_atividade (executor_id);
CREATE INDEX idx_reg_status ON registros_atividade (status);
CREATE INDEX idx_reg_categoria ON registros_atividade (categoria);

CREATE TABLE relatorios (
  id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  formato             formato_relatorio NOT NULL,
  data_inicio_filtro  DATE        NOT NULL,
  data_fim_filtro     DATE        NOT NULL,
  status              status_relatorio NOT NULL DEFAULT 'PROCESSANDO',
  data_geracao        TIMESTAMPTZ,
  arquivo_url         VARCHAR(255),
  total_registros     INT,
  solicitante_id      INT         NOT NULL REFERENCES usuarios(id),
  setor_id            INT         REFERENCES setores(id),
  profissional_id     INT         REFERENCES usuarios(id),
  criado_em           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE notificacoes (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  INT          NOT NULL REFERENCES usuarios(id),
  titulo      VARCHAR(160) NOT NULL,
  mensagem    VARCHAR(500) NOT NULL,
  link        VARCHAR(255),
  lida        BOOLEAN      NOT NULL DEFAULT FALSE,
  criada_em   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_not_usuario ON notificacoes (usuario_id, lida);

CREATE TABLE logs_auditoria (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  INT REFERENCES usuarios(id),
  acao        acao_log    NOT NULL,
  entidade    VARCHAR(60) NOT NULL,
  entidade_id INT,
  detalhes    TEXT,
  ip          VARCHAR(60),
  data_hora   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_log_data ON logs_auditoria (data_hora);

CREATE TABLE IF NOT EXISTS chamados (
  id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo          VARCHAR(160) NOT NULL,
  categoria       VARCHAR(20)  NOT NULL CHECK (categoria IN ('DUVIDA', 'PROBLEMA', 'ACESSO', 'SUGESTAO')),
  prioridade      VARCHAR(10)  NOT NULL DEFAULT 'MEDIA' CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA')),
  status          VARCHAR(20)  NOT NULL DEFAULT 'ABERTO' CHECK (status IN ('ABERTO', 'EM_ATENDIMENTO', 'RESOLVIDO')),
  solicitante_id  INT          NOT NULL REFERENCES usuarios(id),
  criado_em       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolvido_em    TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_chamado_solicitante ON chamados (solicitante_id);
CREATE INDEX IF NOT EXISTS idx_chamado_status ON chamados (status);

CREATE TABLE IF NOT EXISTS chamado_mensagens (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chamado_id  INT         NOT NULL REFERENCES chamados(id) ON DELETE CASCADE,
  autor_id    INT         NOT NULL REFERENCES usuarios(id),
  mensagem    TEXT        NOT NULL,
  criada_em   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_mensagem_chamado ON chamado_mensagens (chamado_id);

CREATE TABLE IF NOT EXISTS chamado_anexos (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mensagem_id  INT          NOT NULL REFERENCES chamado_mensagens(id) ON DELETE CASCADE,
  nome         VARCHAR(160) NOT NULL,
  tipo         VARCHAR(100) NOT NULL,
  tamanho      INT          NOT NULL,
  conteudo     TEXT         NOT NULL,
  criado_em    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_anexo_mensagem ON chamado_anexos (mensagem_id);

